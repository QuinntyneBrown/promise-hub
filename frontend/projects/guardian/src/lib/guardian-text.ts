export type GuardianText = (typeof TEXT)['en'];

export function guardianText(language: GuardianLanguage): GuardianText {
  return TEXT[language] as GuardianText;
}

const LOCALE: Record<GuardianLanguage, string> = { en: 'en-GB', es: 'es', fr: 'fr-CA' };

/** "Thursday 12 November", "jueves 12 de noviembre", "jeudi 12 novembre". */
export function longDate(date: string, language: GuardianLanguage): string {
  const d = date.length === 10 ? new Date(`${date}T12:00:00Z`) : new Date(date);
  return new Intl.DateTimeFormat(LOCALE[language], {
    weekday: 'long',
    day: 'numeric',
    month: 'long',
    timeZone: date.length === 10 ? 'UTC' : undefined,
  })
    .format(d)
    .replace(',', '');
}

/** "9:00 am–3:00 pm" style times in the page's language. */
export function timeRange(startsAt: string, endsAt: string, language: GuardianLanguage): string {
  const f = new Intl.DateTimeFormat(LOCALE[language], { hour: 'numeric', minute: '2-digit' });
  return `${f.format(new Date(startsAt))}–${f.format(new Date(endsAt))}`;
}
